"""Specialist brain definitions — the full capability catalogue.

A "brain" is a specialized capability with an ID, name, role, instructions,
model/provider (optional; falls back to the shared provider), tools, memory
scope, permissions and verification requirements. They are registered into the
Capability Registry at startup and can be extended at runtime without rewriting
the system. Brains do NOT each need a separate model/API — most share the
platform provider; each can be given its own later.

Only a curated set is auto-created as live agents (they share one provider and
are cheap); the rest are definitions ready to activate.
"""

