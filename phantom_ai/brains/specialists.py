def specialist_definitions() -> list[BrainDefinition]:
    out = []
    for s in SPECIALISTS:
        tools = TOOLS.get(s["tools"]) if isinstance(s["tools"], str) else s["tools"]
        out.append(BrainDefinition(
            brain_id=s["brain_id"], name=s["name"], role=s["role"],
            description=s["description"], system_prompt=s["system_prompt"],
            tools=tools, memory_scope=s["brain_id"],
        ))
    return out
